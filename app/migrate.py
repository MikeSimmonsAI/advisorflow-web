"""The migration step. A deploy gate, not a side effect of booting.

    python -m app.migrate

═══════════════════════════════════════════════════════════════════════════
WHY THIS EXISTS
═══════════════════════════════════════════════════════════════════════════
Schema changes used to happen inside the web application's startup handler.
That put every deploy in a position where the only way to find out whether
the schema could be changed was to try to boot — and if the answer was no,
the answer arrived as "Waiting for application startup" for fifteen minutes,
followed by Render tearing down the healthy old instance.

The deployment model that replaces it:

    MIGRATION STEP  →  MIGRATION SUCCEEDS  →  APP STARTS

Render runs this as the service's `preDeployCommand`. A non-zero exit aborts
the deploy BEFORE the new instance is started and BEFORE the old one is
retired, so a database that cannot take the change costs a failed deploy and
a clear message rather than an outage.

═══════════════════════════════════════════════════════════════════════════
WHY THIS IS NOT ALEMBIC (YET), AND WHAT WOULD HAVE HAPPENED IF IT WERE
═══════════════════════════════════════════════════════════════════════════
Alembic IS present, with six revisions — and it is six revisions behind a
schema that `auto_migrate` has carried to 369 columns. `alembic upgrade head`
against production today would do almost nothing, because production is far
ahead of the last revision.

The tempting move is to autogenerate one big catch-up revision and switch. It
was not taken, for a reason that matters more than tidiness: an autogenerated
revision against a live schema is a DROP statement generator. Anything the
models no longer mention — a column kept deliberately, like `deal_value`, or
one another service still writes — becomes a `drop_column` nobody reviews
carefully at deploy time. Trading a startup hang for a data-loss risk is not
hardening.

So the transition is incremental and the ORDER is the part being fixed now:
this step owns migrations, runs them before the app exists, and fails the
deploy on its own. The engine underneath is still `auto_migrate`. Moving that
engine to Alembic afterwards is a mechanical change to ONE function, and it
can be done with the deploy gate already in place instead of while also
inventing it.

WHAT THIS STEP WILL NOT DO. It never terminates a session, never cancels a
query, never drops anything. When the database is not in a state to be
migrated it says so and exits non-zero. Recovery stays a deliberate act.
"""

import logging
import json
import os
import sys

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [migrate] %(levelname)s %(message)s",
)
log = logging.getLogger("migrate")

EXIT_OK = 0
EXIT_PREFLIGHT_BLOCKED = 2
EXIT_REQUIRED_SCHEMA_MISSING = 3
EXIT_FAILED = 4


def _report_preflight(report: dict) -> None:
    log.info("preflight: reachable=%s idle_in_transaction_over_threshold=%s "
             "lock_waits_over_threshold=%s connections=%s/%s",
             report.get("reachable"),
             report["idle_in_transaction"]["over_threshold"],
             report["lock_waits"]["over_threshold"],
             report["connections"].get("used"),
             report["connections"].get("limit"))
    for b in report.get("blockers", []):
        log.error("preflight BLOCKED [%s] %s", b["code"], b["message"])
        log.error("preflight ACTION  [%s] %s", b["code"], b["action"])


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    skip_preflight = "--skip-preflight" in argv

    # Imported here rather than at module scope so that `--help`-style misuse
    # and import errors are distinguishable from database failures.
    from app.auto_migrate import (LAST_RUN, RequiredSchemaMissing,
                                  run_auto_migrations)
    from app.deps import engine
    # THE SAME REGISTRY main.py USES, not a second list. `create_all` only
    # creates tables whose model module has been imported, so a migration step
    # with its own import list would silently stop creating whole families of
    # tables the day somebody adds a model and updates only one of the two
    # places. `app.models.registry` exists precisely so there is one.
    import app.models.registry  # noqa: F401  (imported for side effects)
    from app.models.models import Base
    from app.services import db_health

    # ── 1. PREFLIGHT: is the database in a state to be changed? ───────────
    #
    # READ-ONLY. It reports and refuses; it never clears the way for itself.
    if not skip_preflight:
        report = db_health.preflight(engine)
        _report_preflight(report)
        if not report["safe_to_migrate"]:
            log.error("Refusing to migrate. Nothing was changed. "
                      "Resolve the conditions above and deploy again.")
            return EXIT_PREFLIGHT_BLOCKED
    else:
        # An explicit escape hatch for the case where a human has looked at
        # the evidence and decided to proceed anyway. It is a flag on the
        # command, not an environment variable, so it cannot become the
        # permanent default by accident.
        log.warning("Preflight skipped by --skip-preflight.")

    # ── 2. CREATE ANY WHOLE NEW TABLES ────────────────────────────────────
    # Same call the app made at startup, in the same order, so this step is
    # not a second opinion about what the schema should be.
    try:
        Base.metadata.create_all(bind=engine)
    except Exception as e:                                   # noqa: BLE001
        log.exception("create_all failed")
        log.error("Migration aborted: %s", str(e)[:300])
        return EXIT_FAILED

    # ── 3. COLUMNS, ENUMS, INDEXES ────────────────────────────────────────
    try:
        run_auto_migrations(engine)
    except RequiredSchemaMissing as e:
        # The one condition that must stop a deploy dead. Reported here with
        # the full explanation the exception carries, because this log line
        # is what somebody reads at 2am.
        log.error("%s", e)
        return EXIT_REQUIRED_SCHEMA_MISSING
    except Exception as e:                                   # noqa: BLE001
        log.exception("migration step failed")
        log.error("Migration aborted: %s", str(e)[:300])
        return EXIT_FAILED

    # ── 3b. SCI STAGING MANAGER ACCESS (inert unless explicitly enabled) ──
    # Never changes the exit code: a refused or failed bootstrap must not stop
    # a deploy. It fails closed outside SCI staging (see the module docstring).
    try:
        from app.deps import SessionLocal
        from app.services import sci_staging_bootstrap
        _db = SessionLocal()
        try:
            sci_staging_bootstrap.run(_db)
        finally:
            _db.close()
    except Exception as e:                                   # noqa: BLE001
        log.error("SCI staging bootstrap errored (deploy continues): %s",
                  type(e).__name__)

    # ── 3c. SCI STAGING DEMO FAMILIES (fails closed outside SCI staging) ──
    try:
        from app.deps import SessionLocal
        from app.services import sci_staging_demo
        _db = SessionLocal()
        try:
            log.info("sci staging demo: %s", sci_staging_demo.ensure(_db))
        finally:
            _db.close()
    except Exception as e:                                   # noqa: BLE001
        log.error("SCI staging demo errored (deploy continues): %s", type(e).__name__)

    # ── 3d. INSURANCE RETENTION DEMO (#499) - inert unless switched on ──
    # VINCENT_GREENE_DEMO=1 creates the isolated, synthetic Vincent Greene
    # demo workspace once and seeds it if it has no renewals. It never touches
    # another organization, sends nothing, and creates no usable login.
    # VINCENT_GREENE_DEMO_ADMIN_EMAILS lists EXISTING users to make agency
    # admins of that demo workspace (never God, never a new account).
    # Never changes the exit code.
    if os.environ.get("VINCENT_GREENE_DEMO", "").strip() == "1":
        try:
            from app.deps import SessionLocal
            from app.services.agency import retention_demo
            _db = SessionLocal()
            try:
                emails = os.environ.get("VINCENT_GREENE_DEMO_ADMIN_EMAILS", "").split(",")
                res = retention_demo.ensure_demo(_db, emails)
                _db.commit()
                log.info("retention demo: org=%s created=%s seeded=%s granted=%d",
                         res["organization_id"], res["created"], bool(res["seeded"]), len(res["granted"]))
            except Exception:
                _db.rollback()
                raise
            finally:
                _db.close()
        except Exception as e:                               # noqa: BLE001
            log.error("Retention demo errored (deploy continues): %s: %s", type(e).__name__, str(e)[:200])

    # ── 3e. VOLT MARKETING (#535) - idempotent tenant + project load ──
    # Creates the VOLT Marketing organization and its three projects if they
    # are missing. Never changes a project staff already maintain, creates no
    # login and no applicant. Never changes the exit code.
    try:
        from app.deps import SessionLocal
        from app.services.volt import seed as volt_seed
        _db = SessionLocal()
        try:
            res = volt_seed.ensure(_db)
            _db.commit()
            log.info("volt: org=%s created_org=%s created_program=%s created_projects=%s platform_set=%s",
                     res.get("organization_id"), res["organization"], res["program"], ",".join(res["projects"]) or "-",
                     res.get("platform"))
            if res.get("corrected"):
                log.info("volt: corrected %s", ",".join(res["corrected"]))
            if res.get("identity_set"):
                log.info("volt: email identity set %s", ",".join(res["identity_set"]))
            if res.get("admins_granted"):
                log.info("volt: org admin access granted to %d existing login(s)", res["admins_granted"])
        except Exception:
            _db.rollback()
            raise
        finally:
            _db.close()
    except Exception as e:                                   # noqa: BLE001
        log.error("VOLT seed errored (deploy continues): %s: %s", type(e).__name__, str(e)[:200])

    # ── 3f. WORKSPACE DATA RESET (#507) - inert unless switched on ──
    # WORKSPACE_RESET="<organization id>:<plan|apply|configure>:<run key>" or
    # "<organization id>:rollback:<run id>". `apply` is idempotent per run key
    # (a second deploy with the same value changes nothing); every change is
    # recorded with its before value. Sends nothing, approves nothing, switches
    # nothing on. Never changes the exit code.
    _reset = os.environ.get("WORKSPACE_RESET", "").strip()
    if _reset:
        try:
            from app.deps import SessionLocal
            from app.models.models import Organization
            from app.services.programs import workspace_reset as _wr
            org_id, mode, key = (_reset.split(":", 2) + ["", "", ""])[:3]
            _db = SessionLocal()
            try:
                org = _db.query(Organization).filter(Organization.id == org_id).first()
                if mode == "plan":
                    res = _wr.plan(_db, org)["summary"]
                    log.info("workspace reset plan org=%s: %s", org_id, json.dumps(res, sort_keys=True))
                elif mode == "apply":
                    res = _wr.apply(_db, org, key)
                    log.info("workspace reset apply org=%s run=%s status=%s already=%s changes=%s",
                             org_id, res["run_id"], res["status"], res["already"],
                             json.dumps(res["summary"].get("changes", {}), sort_keys=True))
                elif mode == "configure":
                    # Issue #507 (Nov 7): booking account + rules, the 14-day
                    # campaign, Batch 1 revalidation. Recorded, reversible.
                    from app.services.programs import workspace_configure as _wc
                    res = _wc.configure(_db, org, key,
                                        booking_user_id=os.environ.get("WORKSPACE_BOOKING_USER_ID", "").strip() or None)
                    log.info("workspace configure org=%s run=%s status=%s already=%s summary=%s",
                             org_id, res["run_id"], res["status"], res["already"],
                             json.dumps(res["summary"], sort_keys=True, default=str)[:3500])
                elif mode == "probe":
                    # Read-only readiness check (calendar + sender). Changes nothing.
                    from app.services.programs import workspace_configure as _wc
                    res = _wc.probe_only(_db, org, os.environ.get("WORKSPACE_BOOKING_USER_ID", "").strip() or None)
                    # One line per part so no part is cut off by the log line limit.
                    for _part in sorted(res):
                        _txt = json.dumps(res[_part], sort_keys=True, default=str)
                        for _i in range(0, max(len(_txt), 1), 3000):
                            log.info("workspace probe org=%s part=%s[%d]: %s", org_id, _part, _i // 3000,
                                     _txt[_i:_i + 3000])
                elif mode == "rollback":
                    from app.models.reset_models import WorkspaceResetRun as _Run
                    _r = _db.query(_Run).filter_by(id=key, organization_id=org_id).first()
                    if _r is not None and _r.mode == "configure":
                        from app.services.programs import workspace_configure as _wc
                        res = _wc.rollback(_db, org, key)
                    else:
                        res = _wr.rollback(_db, org, key)
                    log.info("workspace reset rollback org=%s: %s", org_id, json.dumps(res, sort_keys=True))
                else:
                    log.error("workspace reset: unknown mode %r (nothing done)", mode)
            except Exception:
                _db.rollback()
                raise
            finally:
                _db.close()
        except Exception as e:                               # noqa: BLE001
            log.error("Workspace reset errored (deploy continues, nothing half-applied): %s: %s",
                      type(e).__name__, str(e)[:300])

    # ── 4. SAY WHAT HAPPENED ──────────────────────────────────────────────
    log.info("migration outcome=%s elapsed=%ss columns_checked=%s",
             LAST_RUN["outcome"], LAST_RUN["elapsed_seconds"],
             LAST_RUN["columns_checked"])
    if LAST_RUN["missing_optional"]:
        # NOT a deploy failure, and the reason is stated rather than implied:
        # these break one screen, and blocking every deploy on them would
        # hand a contended unrelated table the power to stop all shipping.
        log.warning("DEGRADED: %d non-core column(s) still missing: %s. "
                    "The application will start; features touching them will "
                    "fail until a later run applies them.",
                    len(LAST_RUN["missing_optional"]),
                    ", ".join(LAST_RUN["missing_optional"]))
    log.info("Migration step complete. Starting the application is safe.")
    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
